// One-shot dump for TST-05: run once, writes repo-root 1927EQ.txt (env DUMP_1927EQ=1).
BOOST_AUTO_TEST_CASE(dump_mainnet_genesis_192_7_indices) {
    if (getenv("DUMP_1927EQ") == nullptr) {
        return;
    }
    SelectParams(CBaseChainParams::MAIN);
    const Consensus::Params& consensus = Params().GetConsensus();
    const CBlock& genesis = Params().GenesisBlock();
    CBlockHeader hdr = genesis.GetBlockHeader();
    BOOST_REQUIRE(CheckEquihashSolution(&hdr, consensus));
    const size_t cBitLen = consensus.nEquihashN / (consensus.nEquihashK + 1);
    std::vector<eh_index> idx = GetIndicesFromMinimal(hdr.nSolution, cBitLen);
    BOOST_REQUIRE_EQUAL(idx.size(), 128u);

    const char* outPath = getenv("DUMP_1927EQ");
    std::string path = outPath && *outPath ? outPath : "1927EQ.txt";
    std::ofstream out(path.c_str());
    BOOST_REQUIRE(out.good());
    out << "# Zero mainnet Equihash (192,7) vectors for TST-05\n";
    out << "# Source: Params().GenesisBlock() header (I = CEquihashInput||nNonce)\n";
    out << "# Validate with CheckEquihashSolution / EhIsValidSolution on header state (see pow.cpp)\n";
    out << "# Generated by equihash_tests/dump_mainnet_genesis_192_7_indices\n";
    out << "\n";
    out << "params: n=192 k=7\n";
    out << "label: mainnet_genesis\n";
    out << "height: 0\n";
    out << "nNonce: " << hdr.nNonce.GetHex() << "\n";
    out << "nSolution_hex: " << HexStr(hdr.nSolution) << "\n";
    out << "cBitLen: " << cBitLen << "\n";
    out << "indices_count: " << idx.size() << "\n";
    out << "indices: {\n  ";
    for (size_t i = 0; i < idx.size(); i++) {
        if (i) out << (i % 8 == 0 ? ",\n  " : ", ");
        out << idx[i];
    }
    out << "\n}\n";
    out << "\n# Round-trip: GetMinimalFromIndices(indices, 24) must equal nSolution_hex\n";
    std::vector<unsigned char> roundtrip = GetMinimalFromIndices(idx, cBitLen);
    out << "roundtrip_ok: " << (roundtrip == hdr.nSolution ? "true" : "false") << "\n";
    out.close();
    BOOST_TEST_MESSAGE("Wrote " << path);
}

